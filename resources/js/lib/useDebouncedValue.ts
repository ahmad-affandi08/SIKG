import { useEffect, useState } from 'react';

/** Menunda nilai yang cepat berubah (ketikan pencarian) agar tidak memicu permintaan di setiap tombol. */
export function useDebouncedValue<T>(value: T, delayMs = 250): T {
  const [debounced, setDebounced] = useState(value);

  useEffect(() => {
    const timer = setTimeout(() => {
      setDebounced(value);
    }, delayMs);
    return () => {
      clearTimeout(timer);
    };
  }, [value, delayMs]);

  return debounced;
}
